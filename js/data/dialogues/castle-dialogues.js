export function getDialogueByRank(npcType, rank) {
  const pool = CASTLE_DIALOGUES_BY_RANK[npcType];
  if (!pool) return "...";
  const rankPool = pool[rank] || pool[0];
  return rankPool[Math.floor(Math.random() * rankPool.length)];
}
